export const SOCIAL_VARIANTS = Object.entries(wording).flatMap(([kind, pairs]) =>
  pairs.map(([en, es], i) => ({
    id: `${kind}-${String(i + 1).padStart(2, '0')}`,
    kind,
    en,
    es,
    split: i % 6 < 4 ? 'development' : i % 6 === 4 ? 'validation' : 'heldout',
  })),
);
const groups = new Map();
for (const variant of SOCIAL_VARIANTS) {
  const key = `${variant.kind}:${variant.split}`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(variant);
}
export const renderWording = (text, slots) =>
  text.replace(/\{(\w+)\}/g, (_, slot) => String(slots[slot] ?? ''));
export function chooseSocialWording(kind, split, draw, slots, language = 'en') {
  const group = groups.get(`${kind}:${split}`);
  if (!group) throw new Error(`Unknown social wording group: ${kind}:${split}`);
  const variant = group[Math.min(group.length - 1, Math.floor(draw * group.length))];
  return { id: variant.id, text: renderWording(variant[language === 'es' ? 'es' : 'en'], slots) };
}

export function supplyText(need, quantity, language = 'en') {
  const en = {
    water: 'litres of drinking water',
    food: 'meal portions',
    shelter: 'shelter places',
    medicine: 'units of medicine',
    staff: 'staff members',
    blankets: 'blankets',
    energy: 'energy units',
    sanitation: 'sanitation units',
    fuel: 'litres of fuel',
    rescue: 'rescue units',
  };
  const es = {
    water: 'litros de agua potable',
    food: 'porciones de comida',
    shelter: 'plazas de refugio',
    medicine: 'unidades de medicina',
    staff: 'miembros del equipo',
    blankets: 'mantas',
    energy: 'unidades de energía',
    sanitation: 'unidades de saneamiento',
    fuel: 'litros de combustible',
    rescue: 'unidades de rescate',
  };
  // Only use known labels when the declared unit matches. Preserve custom units.
  const units = {
    water: 'L',
    food: 'portion',
    shelter: 'place',
    staff: 'person',
    fuel: 'L',
    blankets: 'unit',
    medicine: 'unit',
    energy: 'unit',
    sanitation: 'unit',
    rescue: 'unit',
  };
  const label = need.unit === units[need.type] ? (language === 'es' ? es : en)[need.type] : null;
  return label
    ? `${quantity} ${label}`
    : `${quantity} ${need.unit} ${language === 'es' ? 'de' : 'of'} ${need.type}`;
}

