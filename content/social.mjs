export function sourceName(key, drawName, drawInitial) {
  if (key.startsWith('publisher:'))
    return `${publisherNames[Math.floor(drawName * publisherNames.length)]} ${String.fromCharCode(65 + Math.floor(drawInitial * 26))}`;
  return `${firstNames[Math.floor(drawName * firstNames.length)]} ${String.fromCharCode(65 + Math.floor(drawInitial * 26))}.`;
}

// Exact matching for built-in Spanish templates only; original records remain intact.
const translations = SOCIAL_VARIANTS.map((variant) => {
  const slots = [...variant.es.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
  const escaped = variant.es
    .split(/\{\w+\}/g)
    .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  return { ...variant, slots, pattern: new RegExp(`^${escaped.join('(.+?)')}$`) };
});
const supplyLabels = Object.fromEntries(
  [
    'water',
    'food',
    'shelter',
    'medicine',
    'staff',
    'blankets',
    'energy',
    'sanitation',
    'fuel',
    'rescue',
  ].map((type) => {
    const unit =
      { water: 'L', food: 'portion', shelter: 'place', staff: 'person', fuel: 'L' }[type] ?? 'unit';
    return [
      supplyText({ type, unit }, '', 'es').trim(),
      supplyText({ type, unit }, '', 'en').trim(),
    ];
  }),
);
export function socialEnglishText(text) {
  for (const variant of translations) {
    const match = variant.pattern.exec(text);
    if (!match) continue;
    const slots = Object.fromEntries(variant.slots.map((slot, i) => [slot, match[i + 1]]));
    if (slots.supply) {
      for (const [es, en] of Object.entries(supplyLabels))
        if (slots.supply.endsWith(` ${es}`)) slots.supply = slots.supply.slice(0, -es.length) + en;
      slots.supply = slots.supply.replace(/^(\S+) (\S+) de (\S+)$/, '$1 $2 of $3');
    }
    return renderWording(variant.en, slots);
  }
  return text;
}
